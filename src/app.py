"""Main application entry point for the local RAG system.

Wires together ingestion, retrieval, and generation so a user can ask
questions about documents that have already been indexed.

Run from the project root with ``python -m src.app``.
"""
from src.generate import create_rag_chain
from src.ingest import get_embedding_function, get_vector_store


def query_rag(chain, question):
    """Sends a question to the RAG chain and prints the answer.

    Args:
        chain (Runnable): The RAG chain returned by ``create_rag_chain``.
        question (str): The question to ask about the indexed documents.

    Returns:
        str: The answer generated by the LLM.
    """
    print("\nQuerying RAG chain...")
    print(f"Question: {question}")

    response = chain.invoke(question)

    print("\nResponse:")
    print(response)

    return response


def main():
    """Runs a set of sample questions against the indexed documents.

    Reopens the persisted Chroma vector store with the same embedding model
    used during indexing, builds the RAG chain, and asks each sample
    question in turn. Documents must already have been ingested, and the
    Ollama server must be running with the embedding and chat models pulled.
    """
    # Use the exact same embedding model used during indexing.
    embedding_function = get_embedding_function()

    # Reopen the existing Chroma database in data/vectorstore/.
    vector_store = get_vector_store(embedding_function)

    # Build the retriever + prompt + Qwen chain from Step 7.
    rag_chain = create_rag_chain(vector_store)

    # Replace these with questions about your own indexed PDF.
    query_rag(rag_chain, "What is the main topic of the document?")
    query_rag(rag_chain, "Summarize the introduction section.")


if __name__ == "__main__":
    main()