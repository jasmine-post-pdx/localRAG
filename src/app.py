"""Main application entry point for the local RAG system.

Wires together ingestion, retrieval, and generation so a user can ask
questions about documents that have already been indexed.

Run from the project root with ``python -m src.app``.
"""
from rich.markdown import Markdown
from rich.panel import Panel
from rich.text import Text

from src.console import console
from src.generate import create_rag_chain
from src.ingest import get_embedding_function, get_vector_store

DEFAULT_QUESTION = "What are the main topics of the documents?"


def query_rag(chain, question):
    """Sends a question to the RAG chain and prints the answer.

    The answer is rendered as Markdown inside a panel, so formatting the LLM
    uses (bold text, lists) shows as styled text rather than raw symbols.

    Args:
        chain (Runnable): The RAG chain returned by ``create_rag_chain``.
        question (str): The question to ask about the indexed documents.

    Returns:
        str: The answer generated by the LLM.
    """
    console.print("Querying RAG chain...", style="info")
    console.print(f"Question: {question}", style="info")

    response = chain.invoke(question)

    console.print(Panel(Markdown(response), title="Response", border_style="green"))

    return response


def ask(prompt):
    """Asks the user a question and returns the answer with whitespace stripped."""
    return console.input(Text(f"\n{prompt}", style="question")).strip()


def main():
    """Interactively asks questions about the indexed documents.

    Reopens the persisted Chroma vector store with the same embedding model
    used during indexing, builds the RAG chain, then prompts the user for
    questions. An empty first answer uses ``DEFAULT_QUESTION``; an empty
    answer to any later prompt ends the session. Documents must already have been ingested, and the
    Ollama server must be running with the embedding and chat models pulled.
    """
    console.rule("Setup")

    # Use the exact same embedding model used during indexing.
    embedding_function = get_embedding_function()

    # Reopen the existing Chroma database in VECTORSTORE_PATH.
    vector_store = get_vector_store(embedding_function)

    # Build the retriever + prompt + chat model chain from Step 7.
    rag_chain = create_rag_chain(vector_store)

    console.rule("Questions")
    question = ask(f"Ask a question (press Enter for \"{DEFAULT_QUESTION}\"): ")
    query_rag(rag_chain, question or DEFAULT_QUESTION)

    while True:
        question = ask("Ask another question (press Enter to quit): ")
        if not question:
            break
        query_rag(rag_chain, question)

    console.rule("Done")


if __name__ == "__main__":
    main()
