"""Main application entry point for the local RAG system.

Wires together ingestion, retrieval, and generation so a user can ask
questions about documents that have already been indexed, switching between
data stores during the session with ``/use <store>``.

Run from the project root with ``python -m src.app``, adding
``--store <name>`` to start with a store other than the default.
"""
import argparse

from chromadb.errors import InvalidArgumentError
from rich.markdown import Markdown
from rich.panel import Panel
from rich.text import Text

from src import config
from src.console import console
from src.generate import create_rag_chain
from src.ingest import get_embedding_function, get_vector_store

DEFAULT_QUESTION = "What are the main topics of the documents?"
USE_COMMAND = "/use"


def build_rag_chain(store, app_settings):
    """Opens a data store's vector store and builds a RAG chain over it.

    Args:
        store (StoreConfig): The store to answer questions from. Its
            documents must already have been ingested.
        app_settings (AppSettings): Machine-wide settings, for the Ollama
            address.

    Returns:
        Runnable: The RAG chain returned by ``create_rag_chain``.
    """
    console.print(f"Data store: {store.name} ({store.config_path})", style="info")

    # Use the exact same embedding model used during indexing.
    embedding_function = get_embedding_function(
        store.ingest.embedding_model, app_settings.ollama_host,
    )
    vector_store = get_vector_store(embedding_function, store.vectorstore_path)
    return create_rag_chain(vector_store, store.query, app_settings.ollama_host)


def query_rag(chain, question, store):
    """Sends a question to the RAG chain and prints the answer.

    The answer is rendered as Markdown inside a panel, so formatting the LLM
    uses (bold text, lists) shows as styled text rather than raw symbols.

    Args:
        chain (Runnable): The RAG chain returned by ``build_rag_chain``.
        question (str): The question to ask about the indexed documents.
        store (StoreConfig): The store the chain was built for, used in
            error messages.

    Returns:
        str | None: The answer generated by the LLM, or ``None`` if the
        store's vector store was built with a different embedding model.
    """
    console.print("Querying RAG chain...", style="info")
    console.print(f"Question: {question}", style="info")

    try:
        response = chain.invoke(question)
    except InvalidArgumentError as error:
        if "dimension" not in str(error):
            raise
        console.print(
            f"Embedding dimensions are wrong: {error}.\n"
            f"The vector store in {store.vectorstore_path} was built with a "
            f"different embedding model than {store.ingest.embedding_model}. "
            f"Set ingest.embedding_model in {store.config_path} back, re-run "
            f"ingestion, or switch stores with {USE_COMMAND} <store>.",
            style="warning",
        )
        return None

    console.print(Panel(Markdown(response), title="Response", border_style="green"))

    return response


def switch_store(name, current, app_settings):
    """Handles a ``/use`` command.

    With no name, lists the available stores. With a name, loads that store
    and builds a RAG chain for it; naming the current store reloads it, which
    picks up edits to its ``store.toml``.

    Args:
        name (str): The store named after ``/use``, or ``""``.
        current (StoreConfig): The store in use now.
        app_settings (AppSettings): Machine-wide settings.

    Returns:
        tuple[StoreConfig, Runnable] | None: The new store and its chain, or
        ``None`` if the store didn't change.
    """
    if not name:
        stores = [
            f"{store} (current)" if store == current.name else store
            for store in config.list_stores()
        ]
        console.print(f"Data stores: {', '.join(stores)}", style="info")
        return None
    try:
        store = config.load_store(name)
    except RuntimeError as error:
        console.print(str(error), style="warning")
        return None
    console.rule(f"Switching to {store.name}")
    return store, build_rag_chain(store, app_settings)


def ask(prompt):
    """Asks the user a question and returns the answer with whitespace stripped."""
    return console.input(Text(f"\n{prompt}", style="question")).strip()


def main(argv=None):
    """Interactively asks questions about a data store's indexed documents.

    Starts with the store named by ``--store``, or ``RAG_STORE``. Reopens its
    Chroma vector store with the same embedding model used during indexing,
    builds the RAG chain, then prompts the user for questions. An empty
    answer before the first question uses ``DEFAULT_QUESTION``; an empty
    answer after that ends the session. ``/use <store>`` switches stores.
    Documents must already have been ingested, and the Ollama server must be
    running with the embedding and chat models pulled.
    """
    parser = argparse.ArgumentParser(description="Ask questions about a data store's documents.")
    parser.add_argument("--store", help="data store to start with (default: RAG_STORE)")
    args = parser.parse_args(argv)

    app_settings = config.load_app_settings()
    store = config.load_store(args.store or app_settings.default_store)

    console.rule("Setup")
    rag_chain = build_rag_chain(store, app_settings)

    console.rule("Questions")
    console.print(
        f"Type {USE_COMMAND} <store> to switch data stores, or {USE_COMMAND} to list them.",
        style="info",
    )
    asked = False
    while True:
        if asked:
            question = ask(f"Ask another question about {store.name} (press Enter to quit): ")
        else:
            question = ask(
                f"Ask a question about {store.name} (press Enter for \"{DEFAULT_QUESTION}\"): "
            )

        if question.startswith("/"):
            command, _, name = question.partition(" ")
            if command == USE_COMMAND:
                switched = switch_store(name.strip(), store, app_settings)
                if switched:
                    store, rag_chain = switched
            else:
                console.print(
                    f"Unknown command {command}. Type {USE_COMMAND} <store> to switch "
                    "data stores.",
                    style="warning",
                )
            continue

        if not question:
            if asked:
                break
            question = DEFAULT_QUESTION
        query_rag(rag_chain, question, store)
        asked = True

    console.rule("Done")


if __name__ == "__main__":
    main()
